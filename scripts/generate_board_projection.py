#!/usr/bin/env python3
"""Preserve Rich4's exact GPL upstream camera constants, including old rounding.

Usage: python3 scripts/generate_board_projection.py .local/upstream/asm/rich4.asm
The generated C++ needs neither the original executable nor this assembly file.
"""

import argparse
import hashlib
from pathlib import Path
import struct


def numeric_data(source: str, first: str, last: str) -> bytes:
    start = source.index("\n" + first + ":")
    end = source.index("\n" + last + ":", start)
    result = bytearray()
    for line in source[start:end].splitlines():
        fields = line.partition(";")[0].split()
        if fields and fields[0] in ("db", "dw", "dd"):
            result.extend(struct.pack("<" + {"db": "B", "dw": "H", "dd": "I"}[fields[0]],
                                      int(fields[1], 0)))
    return bytes(result)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("assembly", type=Path)
    parser.add_argument("--output", type=Path, default=Path("src/board_projection_tables.inc"))
    args = parser.parse_args()
    source = args.assembly.read_text()
    projection = numeric_data(source, "ref_0046ccf0", "ref_00473610")
    traversal = numeric_data(source, "ref_00473610", "ref_00474910")
    fractions = numeric_data(source, "ref_00474910", "ref_00474930")
    if (len(projection), len(traversal), len(fractions)) != (26912, 4864, 32):
        raise ValueError("upstream camera table dimensions have changed")
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// Rich4 reverse engineering by Iru Cai <mytbk920423@gmail.com>.",
        "// Generated by scripts/generate_board_projection.py from upstream asm/rich4.asm.",
        "// Addresses: projection 0x46ccf0, traversal 0x473610, fractional basis 0x474910.",
        "// Preserve these data tables: a new floating-point matrix changes pixel rounding.",
        "// Raw constants SHA256: " + hashlib.sha256(projection + traversal + fractions).hexdigest(),
        "constexpr std::array<std::array<Point, 841>, 8> camera_grid{{",
    ]
    for rotation in range(8):
        lines.append("    {{ // View " + str(rotation))
        for y in range(29):
            points = [struct.unpack_from("<hh", projection, rotation * 3364 + (y * 29 + x) * 4)
                      for x in range(29)]
            for first in range(0, 29, 6):
                lines.append("        " + ", ".join("Point{%d, %d}" % (x, y)
                                                   for y, x in points[first:first + 6]) + ",")
        lines.append("    }},")
    lines.extend(["}};", "", "constexpr std::array<std::array<Point, 304>, 8> ground_order{{"])
    for rotation in range(8):
        lines.append("    {{ // View " + str(rotation))
        points = [struct.unpack_from("bb", traversal, rotation * 608 + i * 2) for i in range(304)]
        for first in range(0, 304, 8):
            lines.append("        " + ", ".join("Point{%d, %d}" % (x, y)
                                               for y, x in points[first:first + 8]) + ",")
        lines.append("    }},")
    lines.extend(["}};", "", "constexpr std::array<std::array<int, 4>, 8> fractional_basis{{"])
    for row in struct.iter_unpack("bbbb", fractions):
        lines.append("    {{" + ", ".join(str(v) for v in row) + "}},")
    lines.extend(["}};", ""])
    args.output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
